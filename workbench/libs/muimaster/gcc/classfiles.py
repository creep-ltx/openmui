#!/usr/bin/env python3
"""Generate the glue for classes built as files of their own (classfile.h).

header OUT SRC...   classfiles.h (which class is in which file) and, next to
                    it, cf/<src>.flags with the -D options for classfile.c
iface NM OUTDIR LIBOBJ... -- CFOBJ...
                    classtable.c (the library's function table) and
                    stubs/*.s (one jump per function for the class files),
                    both stamped with a checksum of the function list
"""
import os
import re
import subprocess
import sys
import zlib

# Data the class files may share: copied at load time (classfile.h)
BASES = {
    'SysBase', 'DOSBase', 'UtilityBase', 'GfxBase', 'IntuitionBase',
    'LayersBase', 'KeymapBase', 'GadToolsBase', 'LocaleBase', 'CyberGfxBase',
    'AslBase', 'CxBase', 'RexxSysBase', 'DataTypesBase', 'IFFParseBase',
    'DiskfontBase', 'IconBase', 'WorkbenchBase', 'MathIeeeDoubBasBase',
    'MathIeeeDoubTransBase', 'MUIMasterBase',
}


def class_names(src, headers):
    """The class names (MUIC_ strings) of the descriptions in src."""
    text = open(src, encoding='latin-1').read()
    names = []
    for desc, muic in re.findall(
            r'const struct __MUIBuiltinClass\s+(_MUI_\w+_desc)\s*=\s*\{\s*(\w+)',
            text):
        if muic.startswith('"'):
            names.append((desc, muic.strip('"')))
            continue
        for h in headers:
            m = re.search(r'#define\s+%s\s+"([^"]+)"' % muic, h)
            if m:
                names.append((desc, m.group(1)))
                break
        else:
            sys.exit('classfiles.py: %s: %s not found' % (src, muic))
    if not names:
        sys.exit('classfiles.py: %s: no class description' % src)
    return names


def header(out, srcs):
    here = os.path.dirname(os.path.abspath(__file__))
    top = os.path.dirname(here)
    headers = []
    for d in (top, os.path.join(top, 'classes')):
        for f in sorted(os.listdir(d)):
            if f.endswith('.h'):
                headers.append(open(os.path.join(d, f), encoding='latin-1').read())
    files, classes = [], []
    flagdir = os.path.join(os.path.dirname(out), 'cf')
    os.makedirs(flagdir, exist_ok=True)
    for i, src in enumerate(srcs):
        base = os.path.splitext(os.path.basename(src))[0]
        fname = base[0].upper() + base[1:] + '.mui'
        files.append(fname)
        names = class_names(src, headers)
        for desc, name in names:
            classes.append((name, i))
        descs = ','.join(d for d, n in names)
        ptrs = ','.join('&' + d for d, n in names)
        with open(os.path.join(flagdir, base + '.flags'), 'w') as f:
            f.write('-DZCF_NAME="%s" -DZCF_DESCS=%s -DZCF_DESC_PTRS=%s\n'
                    % (fname, descs, ptrs))
    with open(out + '.tmp', 'w') as f:
        f.write('/* Generated by gcc/classfiles.py: classes in files of their own */\n')
        f.write('#define ZUNE_CLASSFILE_NFILES %d\n' % len(files))
        f.write('#define ZUNE_CLASSFILE_FILES(X) %s\n'
                % ' '.join('X("%s")' % n for n in files))
        f.write('#define ZUNE_CLASSFILE_CLASSES(X) %s\n'
                % ' '.join('X("%s", %d)' % c for c in classes))
    os.replace(out + '.tmp', out)


def symbols(nm, objs, defined):
    args = [nm, '-g', '--defined-only' if defined else '-u'] + objs
    out = subprocess.run(args, capture_output=True, text=True, check=True).stdout
    syms = {}
    for line in out.splitlines():
        parts = line.split()
        if defined and len(parts) == 3:
            syms[parts[2]] = parts[1]
        elif not defined and len(parts) == 2 and parts[0] == 'U':
            syms[parts[1]] = 'U'
    return syms


def iface(nm, outdir, libobjs, cfobjs):
    lib = symbols(nm, libobjs, True)
    need = symbols(nm, cfobjs, False) if cfobjs else {}
    funcs = []
    for sym in sorted(need):
        if sym not in lib:
            continue                    # libnix, libgcc: linked into the file
        if lib[sym] in 'Tt':
            funcs.append(sym)
        elif sym[1:] not in BASES:
            sys.exit('classfiles.py: class files use library data %s' % sym)
        elif sym == '_CyberGfxBase':
            # Opened by the library after a file may have copied the bases,
            # and not through zune_lazylib_open(): the copy could stay NULL.
            sys.exit('classfiles.py: a class file uses CyberGfxBase; keep it built in')
    ident = zlib.crc32('\n'.join(funcs).encode()) & 0xffffffff
    with open(os.path.join(outdir, 'classtable.c'), 'w') as f:
        f.write('/* Generated by gcc/classfiles.py */\n#include "classfile.h"\n')
        for sym in funcs:
            f.write('extern char zcf%d[] __asm("%s");\n' % (funcs.index(sym), sym))
        f.write('#define ZCF_BASE(n) extern void *n;\nZUNE_CLASSFILE_BASES(ZCF_BASE)\n')
        f.write('static const APTR funcs[] = {\n')
        for i in range(len(funcs)):
            f.write('    (APTR)zcf%d,\n' % i)
        f.write('    0\n};\n')
        f.write('#define ZCF_BASEADDR(n) (APTR *)&n,\n')
        f.write('const struct ZuneClassFileIface zune_classfile_iface = {\n')
        f.write('    ZUNE_CLASSFILE_MAGIC, 0x%08x, %d, funcs,\n' % (ident, len(funcs)))
        f.write('    { ZUNE_CLASSFILE_BASES(ZCF_BASEADDR) }\n};\n')
    # One jump per file, so that a class file links only the ones it calls
    stubdir = os.path.join(outdir, 'stubs')
    os.makedirs(stubdir, exist_ok=True)
    for f in os.listdir(stubdir):
        os.remove(os.path.join(stubdir, f))
    for i, sym in enumerate(funcs):
        with open(os.path.join(stubdir, 'f%03d.s' % i), 'w') as f:
            f.write('| Generated by gcc/classfiles.py\n\t.text\n'
                    '\t.globl\t%s\n%s:\n\tmove.l\t_zune_cf_iface,a0\n'
                    '\tmove.l\t12(a0),a0\n\tmove.l\t%d(a0),a0\n\tjmp\t(a0)\n'
                    % (sym, sym, i * 4))
    with open(os.path.join(stubdir, 'id.s'), 'w') as f:
        f.write('| Generated by gcc/classfiles.py\n\t.text\n')
        f.write('\t.globl\t_zune_cf_id\n_zune_cf_id:\n\t.long\t0x%08x\n' % ident)
        f.write('\t.globl\t_zune_cf_count\n_zune_cf_count:\n\t.long\t%d\n'
                % len(funcs))


def main():
    if sys.argv[1] == 'header':
        header(sys.argv[2], sys.argv[3:])
    elif sys.argv[1] == 'iface':
        nm, outdir = sys.argv[2], sys.argv[3]
        rest = sys.argv[4:]
        split = rest.index('--')
        iface(nm, outdir, rest[:split], rest[split + 1:])
    else:
        sys.exit(__doc__)


if __name__ == '__main__':
    main()
